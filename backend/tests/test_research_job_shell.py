"""Execute the exact job shell payloads, including multiline commands."""

import shlex
import subprocess
import time
from pathlib import Path
from types import SimpleNamespace

import pytest

from backend import research_host as host
from backend import research_remote as remote
from backend import research_sandbox as sandbox
from backend.config import Settings


@pytest.mark.parametrize("runner", ["host", "ssh"])
@pytest.mark.parametrize("exit_code,pipeline", [(0, False), (7, False), (9, True)])
def test_jobs_record_heredoc_output_and_exit_without_a_final_newline(
    tmp_path, monkeypatch, runner, exit_code, pipeline
):
    settings = Settings(storage=str(tmp_path / "files"), testing=True)
    project = SimpleNamespace(id="project")
    command = (
        "python3 - <<'PY'"
        + (" | cat" if pipeline else "")
        + "\nimport sys\nprint('heredoc-output')\n"
        + f"sys.exit({exit_code})\nPY"
    )
    assert not command.endswith("\n")
    job = SimpleNamespace(id="job", command=command)

    if runner == "host":
        host.start(settings, None, {}, project, job)
        deadline = time.monotonic() + 5
        while time.monotonic() < deadline:
            state = host.state(job)
            if state is not sandbox.GONE and not state["Running"]:
                break
            time.sleep(0.02)
        assert state == {"Running": False, "ExitCode": exit_code}
        assert host.logs(job).strip() == "heredoc-output"
        assert Path(job.remote["exit"]).read_text().strip() == str(exit_code)
    else:
        base = tmp_path / "remote control"
        work = tmp_path / "remote work"
        work.mkdir()
        monkeypatch.setattr(remote, "prepare", lambda *args: str(base))
        completed = []

        def execute_payload(_item, script, timeout=120):
            if script.startswith("mkdir "):
                return subprocess.run(
                    ["bash", "-c", script], capture_output=True, text=True, check=True
                )
            # Replace only SSH/detachment, then execute the exact bash -c payload
            # generated by remote.start. This needs neither an SSH server nor
            # Linux's setsid executable on the test machine.
            launch = shlex.split(script)
            index = launch.index("bash")
            assert launch[index + 1] == "-c"
            completed.append(
                subprocess.run(
                    ["bash", "-c", launch[index + 2]],
                    cwd=work,
                    capture_output=True,
                    text=True,
                    timeout=5,
                )
            )
            return subprocess.CompletedProcess(script, 0, "12345\n", "")

        monkeypatch.setattr(remote, "ssh", execute_payload)
        remote.start(
            settings,
            None,
            {"host": "unused", "remote_dir": str(base), "workspace_path": str(work)},
            project,
            job,
        )
        assert completed[0].returncode == 0, completed[0].stderr
        assert completed[0].stdout.strip() == "heredoc-output"
        assert (base / "runs" / job.id / ".exit").read_text().strip() == str(exit_code)
